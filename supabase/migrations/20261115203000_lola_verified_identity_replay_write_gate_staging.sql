-- Lola Stage 10: authorization registry + write-time replay guard.
-- STAGING CANDIDATE ONLY. Do not apply to any hosted Supabase project
-- without separate, explicit database/project deployment approval.
--
-- Database-side consent locks close the gap between Python's last
-- authorization check and the atomic encrypted-cursor RPC transaction.
-- No end-user Data API grants; service-role backend only; no seeded grants.
-- A durable cursor is NOT evidence that anyone did not respond.
BEGIN;

CREATE TABLE public.lola_channel_authorizations (
    company_id UUID NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    employee_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    channel TEXT NOT NULL CHECK (channel IN ('email','whatsapp_business')),
    provider_name TEXT NOT NULL
      CHECK (provider_name IN ('gmail','outlook','meta_whatsapp_business')),
    provider_identity_ref TEXT NOT NULL
      CHECK (length(btrim(provider_identity_ref)) BETWEEN 1 AND 200
             AND provider_identity_ref !~ '[[:cntrl:]]'),
    -- Keyed HMAC-SHA256 of company, employee, provider, provider identity
    -- generated by the same private CursorVault as the replay adapter.
    provider_identity_sha256 TEXT NOT NULL
      CHECK (provider_identity_sha256 ~ '^[0-9a-f]{64}$'),
    provider_verification_state TEXT NOT NULL DEFAULT 'pending'
      CHECK (provider_verification_state IN ('pending','verified','revoked')),
    connector_authorization_state TEXT NOT NULL DEFAULT 'disconnected'
      CHECK (connector_authorization_state IN ('disconnected','connected','revoked')),
    employee_consent_at TIMESTAMPTZ,
    employee_consent_revoked_at TIMESTAMPTZ,
    provider_verified_at TIMESTAMPTZ,
    authorization_expires_at TIMESTAMPTZ,
    source_revision TEXT NOT NULL
      CHECK (length(btrim(source_revision)) BETWEEN 1 AND 200
             AND source_revision !~ '[[:cntrl:]]'),
    PRIMARY KEY (company_id,employee_id,channel),
    CONSTRAINT lola_auth_channel_provider CHECK (
      (channel='email' AND provider_name IN ('gmail','outlook'))
      OR (channel='whatsapp_business' AND provider_name='meta_whatsapp_business')
    )
);
CREATE INDEX lola_auth_active_employee_idx
    ON public.lola_channel_authorizations(company_id,employee_id,channel);

CREATE TABLE public.lola_verified_case_links (
    company_id UUID NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    employee_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    contact_id TEXT NOT NULL
      CHECK (length(btrim(contact_id)) BETWEEN 1 AND 200
             AND contact_id !~ '[[:cntrl:]]'),
    work_item_id TEXT NOT NULL
      CHECK (length(btrim(work_item_id)) BETWEEN 1 AND 200
             AND work_item_id !~ '[[:cntrl:]]'),
    email_provider_contact_ref TEXT NOT NULL
      CHECK (length(btrim(email_provider_contact_ref)) BETWEEN 1 AND 200),
    whatsapp_provider_contact_ref TEXT NOT NULL
      CHECK (length(btrim(whatsapp_provider_contact_ref)) BETWEEN 1 AND 200),
    link_verification_state TEXT NOT NULL DEFAULT 'candidate'
      CHECK (link_verification_state IN ('candidate','verified','revoked')),
    verification_source TEXT NOT NULL DEFAULT 'unverified'
      CHECK (verification_source IN ('unverified','provider_plus_employee')),
    employee_confirmed_at TIMESTAMPTZ,
    link_verified_at TIMESTAMPTZ,
    link_revoked_at TIMESTAMPTZ,
    verification_expires_at TIMESTAMPTZ,
    mapping_revision TEXT NOT NULL
      CHECK (length(btrim(mapping_revision)) BETWEEN 1 AND 200
             AND mapping_revision !~ '[[:cntrl:]]'),
    PRIMARY KEY (company_id,employee_id,contact_id,work_item_id)
);
CREATE INDEX lola_verified_links_scoped_idx
    ON public.lola_verified_case_links(company_id,employee_id,link_verification_state);

CREATE TABLE public.lola_authorized_email_resources (
    company_id UUID NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    employee_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    provider_name TEXT NOT NULL CHECK (provider_name IN ('gmail','outlook')),
    provider_identity_sha256 TEXT NOT NULL
      CHECK (provider_identity_sha256 ~ '^[0-9a-f]{64}$'),
    resource_sha256 TEXT NOT NULL
      CHECK (resource_sha256 ~ '^[0-9a-f]{64}$'),
    verified_at TIMESTAMPTZ NOT NULL,
    authorization_expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    verification_source TEXT NOT NULL
      CHECK (verification_source IN ('oauth_principal_and_employee','provider_folder_confirmed')),
    PRIMARY KEY (
      company_id,employee_id,provider_name,provider_identity_sha256,resource_sha256
    )
);

ALTER TABLE public.lola_channel_authorizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lola_verified_case_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lola_authorized_email_resources ENABLE ROW LEVEL SECURITY;
-- No browser-user policies. Never grant anon/authenticated access.
REVOKE ALL ON public.lola_channel_authorizations
    FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON public.lola_verified_case_links
    FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON public.lola_authorized_email_resources
    FROM PUBLIC,anon,authenticated,service_role;
GRANT SELECT,INSERT,UPDATE ON public.lola_channel_authorizations TO service_role;
GRANT SELECT,INSERT,UPDATE ON public.lola_verified_case_links TO service_role;
GRANT SELECT,INSERT,UPDATE ON public.lola_authorized_email_resources TO service_role;

-- Enforce active employee, BOTH independently verified channels, signed
-- employee consent, work-item mapping and provider resource at the actual
-- database checkpoint write. Lock rows FOR SHARE so concurrent revocation
-- cannot commit between this check and the cursor/event transaction.
CREATE FUNCTION public.lola_guard_provider_replay_checkpoint()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $body$
DECLARE
    v_email public.lola_channel_authorizations%ROWTYPE;
    v_whatsapp public.lola_channel_authorizations%ROWTYPE;
    v_employee_id UUID;
    v_link_present BOOLEAN := FALSE;
    v_resource_present BOOLEAN := FALSE;
    v_now TIMESTAMPTZ := transaction_timestamp();
BEGIN
    -- Do not permit reassigning a checkpoint to another tenant or mailbox.
    IF TG_OP='UPDATE' AND (
        OLD.company_id IS DISTINCT FROM NEW.company_id
        OR OLD.employee_id IS DISTINCT FROM NEW.employee_id
        OR OLD.provider IS DISTINCT FROM NEW.provider
        OR OLD.provider_identity_sha256 IS DISTINCT FROM NEW.provider_identity_sha256
        OR OLD.resource_sha256 IS DISTINCT FROM NEW.resource_sha256
        OR OLD.mapping_revision IS DISTINCT FROM NEW.mapping_revision
    ) THEN
        RAISE EXCEPTION 'Provider replay checkpoint scope immutable';
    END IF;

    SELECT u.id INTO v_employee_id
      FROM public.users u
      WHERE u.id=NEW.employee_id AND u.company_id=NEW.company_id
        AND u.is_active IS TRUE
        AND u.role IN ('owner','manager','back_office','sales_rep')
      FOR SHARE;
    IF v_employee_id IS NULL THEN
        RAISE EXCEPTION 'Provider replay employee not currently authorized';
    END IF;

    SELECT a.* INTO v_email
      FROM public.lola_channel_authorizations a
      WHERE a.company_id=NEW.company_id
        AND a.employee_id=NEW.employee_id AND a.channel='email'
      FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Verified employee email authorization missing';
    END IF;
    SELECT a.* INTO v_whatsapp
      FROM public.lola_channel_authorizations a
      WHERE a.company_id=NEW.company_id
        AND a.employee_id=NEW.employee_id AND a.channel='whatsapp_business'
      FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Verified employee WhatsApp authorization missing';
    END IF;

    IF v_email.provider_name IS DISTINCT FROM NEW.provider
       OR v_email.provider_identity_sha256 IS DISTINCT FROM NEW.provider_identity_sha256
       OR v_email.provider_verification_state IS DISTINCT FROM 'verified'
       OR v_email.connector_authorization_state IS DISTINCT FROM 'connected'
       OR v_email.employee_consent_at IS NULL
       OR v_email.employee_consent_at > v_now
       OR v_email.employee_consent_revoked_at IS NOT NULL
       OR v_email.provider_verified_at IS NULL
       OR v_email.provider_verified_at > v_now
       OR v_email.authorization_expires_at IS NULL
       OR v_email.authorization_expires_at <= v_now
       OR v_whatsapp.provider_verification_state IS DISTINCT FROM 'verified'
       OR v_whatsapp.connector_authorization_state IS DISTINCT FROM 'connected'
       OR v_whatsapp.employee_consent_at IS NULL
       OR v_whatsapp.employee_consent_at > v_now
       OR v_whatsapp.employee_consent_revoked_at IS NOT NULL
       OR v_whatsapp.provider_verified_at IS NULL
       OR v_whatsapp.provider_verified_at > v_now
       OR v_whatsapp.authorization_expires_at IS NULL
       OR v_whatsapp.authorization_expires_at <= v_now
    THEN
        RAISE EXCEPTION 'Employee provider consent or identity no longer verified';
    END IF;

    -- No guessed mailbox or Graph folder: the exact keyed resource must be
    -- registered independently and still authorized at commit time.
    SELECT TRUE INTO v_resource_present
      FROM public.lola_authorized_email_resources r
      WHERE r.company_id=NEW.company_id AND r.employee_id=NEW.employee_id
        AND r.provider_name=NEW.provider
        AND r.provider_identity_sha256=NEW.provider_identity_sha256
        AND r.resource_sha256=NEW.resource_sha256
        AND r.revoked_at IS NULL
        AND r.verified_at <= v_now AND r.authorization_expires_at > v_now
      FOR SHARE;
    IF v_resource_present IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Provider mailbox or folder authorization unavailable';
    END IF;

    -- Exactly match the Stage 5 Python verified-case fingerprint:
    -- SHA256(company,employee,contact,work_item,link_revision,
    --        'email:' || email_source_revision,
    --        'whatsapp_business:' || whatsapp_source_revision)
    -- where fields are separated by ASCII LF. Channel order is stable.
    SELECT TRUE INTO v_link_present
      FROM public.lola_verified_case_links l
      WHERE l.company_id=NEW.company_id AND l.employee_id=NEW.employee_id
        AND l.link_verification_state='verified'
        AND l.verification_source='provider_plus_employee'
        AND l.employee_confirmed_at IS NOT NULL AND l.employee_confirmed_at <= v_now
        AND l.link_verified_at IS NOT NULL AND l.link_verified_at <= v_now
        AND l.link_revoked_at IS NULL
        AND l.verification_expires_at > v_now
        AND pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(
            pg_catalog.concat_ws(E'\n',
              l.company_id::text, l.employee_id::text,
              l.contact_id, l.work_item_id, l.mapping_revision,
              'email:' || v_email.source_revision,
              'whatsapp_business:' || v_whatsapp.source_revision
            ), 'UTF8'
        )), 'hex') = NEW.mapping_revision
      LIMIT 1 FOR SHARE;
    IF v_link_present IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Verified cross-channel work-item mapping unavailable';
    END IF;

    RETURN NEW;
END;
$body$;

REVOKE ALL ON FUNCTION public.lola_guard_provider_replay_checkpoint()
    FROM PUBLIC,anon,authenticated,service_role;
-- Trigger execution uses table owner's privilege; service_role can also
-- perform authorized backend-only data writes; no browser execution.
GRANT EXECUTE ON FUNCTION public.lola_guard_provider_replay_checkpoint()
    TO service_role;
CREATE TRIGGER lola_provider_replay_authorization_gate
  BEFORE INSERT OR UPDATE ON public.lola_provider_replay_checkpoints
  FOR EACH ROW EXECUTE FUNCTION public.lola_guard_provider_replay_checkpoint();

-- Event rows cannot be manufactured without a matching committed checkpoint
-- from the same company / employee / provider / resource / replay generation.
ALTER TABLE public.lola_provider_replay_events
  ADD CONSTRAINT lola_replay_events_checkpoint_fk
  FOREIGN KEY (
    company_id,employee_id,provider,provider_identity_sha256,resource_sha256
  ) REFERENCES public.lola_provider_replay_checkpoints (
    company_id,employee_id,provider,provider_identity_sha256,resource_sha256
  ) ON DELETE RESTRICT;

CREATE FUNCTION public.lola_guard_provider_replay_event()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path=pg_catalog,public
AS $body$
DECLARE
    v_exists BOOLEAN := FALSE;
BEGIN
    SELECT TRUE INTO v_exists FROM public.lola_provider_replay_checkpoints c
    WHERE c.company_id=NEW.company_id AND c.employee_id=NEW.employee_id
      AND c.provider=NEW.provider
      AND c.provider_identity_sha256=NEW.provider_identity_sha256
      AND c.resource_sha256=NEW.resource_sha256
      AND c.replay_digest=NEW.replay_digest
    FOR SHARE;
    IF v_exists IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Uncommitted or mismatched provider replay event';
    END IF;
    RETURN NEW;
END;
$body$;
REVOKE ALL ON FUNCTION public.lola_guard_provider_replay_event()
    FROM PUBLIC,anon,authenticated,service_role;
GRANT EXECUTE ON FUNCTION public.lola_guard_provider_replay_event()
    TO service_role;
CREATE TRIGGER lola_provider_replay_event_scope_gate
  BEFORE INSERT ON public.lola_provider_replay_events
  FOR EACH ROW EXECUTE FUNCTION public.lola_guard_provider_replay_event();

COMMIT;
