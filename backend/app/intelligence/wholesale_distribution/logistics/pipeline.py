"""
Shared data models for the 9-stage Logistics & Procurement pipeline.

Every stage reads from and writes to these structures.
They are plain dataclasses (no ORM) — the API layer handles DB persistence.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import date, datetime, timezone
from enum import Enum
from typing import Any, Optional


# ─── Enums ───────────────────────────────────────────────────────────────────


class SupplyChainType(str, Enum):
    OVERSEAS = "overseas"    # Profile A: 6–14 week lead time, ocean freight
    DOMESTIC = "domestic"    # Profile B: same-day to 2 weeks


class UrgencyLevel(str, Enum):
    GREEN = "green"    # reorder within 2 weeks is fine
    YELLOW = "yellow"  # reorder this week
    RED = "red"        # reorder immediately — stockout risk


class ProcurementStage(str, Enum):
    DEMAND_MONITORING = "1_demand_monitoring"
    PO_GENERATION = "2_po_generation"
    VENDOR_RESPONSE = "3_vendor_response"
    FREIGHT_BOOKING = "4_freight_booking"
    IN_TRANSIT = "5_in_transit"
    AT_PORT = "6_at_port"
    CUSTOMS_CLEARANCE = "6b_customs_clearance"
    DRAYAGE = "7_drayage"
    WAREHOUSE_RECEIPT = "7b_warehouse_receipt"
    COST_RECONCILIATION = "8_cost_reconciliation"
    COMPLETE = "9_complete"


class CycleStatus(str, Enum):
    OPEN = "open"
    ON_TRACK = "on_track"
    DELAYED = "delayed"
    NEEDS_ATTENTION = "needs_attention"
    COMPLETE = "complete"
    CANCELLED = "cancelled"


class CommunicationDirection(str, Enum):
    OUTBOUND = "outbound"
    INBOUND = "inbound"


# ─── SKU Profile ──────────────────────────────────────────────────────────────


@dataclass
class SKUProfile:
    """
    Supply chain profile for a single SKU.
    This is the master configuration that drives all pipeline logic for this SKU.
    """
    sku: str
    name: str
    supplier_id: str
    supplier_name: str
    supply_chain_type: SupplyChainType
    origin_country: str = ""
    origin_port: str = ""
    destination_port: str = ""
    hs_code: str = ""

    # Service level target: A=0.97, B=0.93, C=0.88
    service_level_target: float = 0.95
    sku_tier: str = "B"   # A | B | C

    # Cost
    unit_cost_fob: float = 0.0           # FOB cost per unit
    cases_per_pallet: int = 60
    cases_per_20ft_container: int = 800
    cases_per_40ft_container: int = 1_600
    cases_per_40hc_container: int = 1_800
    minimum_order_cases: int = 0

    # Current stock state (updated from QB sync)
    stock_on_hand: int = 0
    stock_committed: int = 0            # allocated to open orders
    stock_in_transit: int = 0           # already on order / in transit

    def to_dict(self) -> dict:
        return {
            "sku": self.sku,
            "name": self.name,
            "supplier_id": self.supplier_id,
            "supplier_name": self.supplier_name,
            "supply_chain_type": self.supply_chain_type.value,
            "origin_country": self.origin_country,
            "service_level_target": self.service_level_target,
            "sku_tier": self.sku_tier,
            "unit_cost_fob": self.unit_cost_fob,
            "stock_on_hand": self.stock_on_hand,
            "stock_committed": self.stock_committed,
            "stock_in_transit": self.stock_in_transit,
        }


# ─── Stage 1: Reorder Decision Package ───────────────────────────────────────


@dataclass
class DemandProjection:
    """14-week forward demand projection with confidence range."""
    weekly_demand: list[float]          # 14 values
    weekly_demand_low: list[float]      # lower bound (10th percentile)
    weekly_demand_high: list[float]     # upper bound (90th percentile)
    seasonal_adjustment_applied: bool = False
    confidence: float = 0.7

    @property
    def total_14_week(self) -> float:
        return sum(self.weekly_demand)

    @property
    def avg_weekly(self) -> float:
        return self.total_14_week / 14 if self.weekly_demand else 0.0


@dataclass
class ReorderDecisionPackage:
    """
    Complete reorder decision package generated by Stage 1.
    Contains everything the logistics manager needs to act.
    """
    id: str = field(default_factory=lambda: str(uuid.uuid4()))
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    sku_profile: Optional[SKUProfile] = None
    urgency: UrgencyLevel = UrgencyLevel.GREEN

    # Current position
    net_available: int = 0              # on_hand - committed + in_transit
    days_of_supply: float = 0.0
    projected_stockout_date: Optional[str] = None

    # Demand
    demand_projection: Optional[DemandProjection] = None
    avg_daily_demand: float = 0.0

    # Recommended order
    recommended_qty: int = 0
    recommended_qty_reasoning: str = ""
    container_fill_pct: float = 0.0    # how full the container would be
    container_suggestion: str = ""     # upsell suggestion if < 80%

    # Lead time
    expected_lead_time_days: float = 0.0
    lead_time_p80_days: float = 0.0    # 80th percentile (planning lead time)

    # Cost estimate
    estimated_fob_cost: float = 0.0
    estimated_freight_cost: float = 0.0
    estimated_landed_cost: float = 0.0
    last_order_reference: str = ""
    price_change_flag: bool = False
    price_change_note: str = ""

    # Resolution
    approved: bool = False
    approved_qty: Optional[int] = None
    approved_by: str = ""
    dismissed: bool = False
    dismiss_reason: str = ""

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "created_at": self.created_at,
            "sku": self.sku_profile.sku if self.sku_profile else None,
            "sku_name": self.sku_profile.name if self.sku_profile else None,
            "supplier": self.sku_profile.supplier_name if self.sku_profile else None,
            "supply_chain_type": self.sku_profile.supply_chain_type.value if self.sku_profile else None,
            "urgency": self.urgency.value,
            "net_available": self.net_available,
            "days_of_supply": round(self.days_of_supply, 1),
            "projected_stockout_date": self.projected_stockout_date,
            "avg_daily_demand": round(self.avg_daily_demand, 2),
            "recommended_qty": self.recommended_qty,
            "recommended_qty_reasoning": self.recommended_qty_reasoning,
            "container_fill_pct": round(self.container_fill_pct, 1),
            "container_suggestion": self.container_suggestion,
            "expected_lead_time_days": round(self.expected_lead_time_days, 0),
            "estimated_landed_cost": round(self.estimated_landed_cost, 2),
            "price_change_flag": self.price_change_flag,
            "price_change_note": self.price_change_note,
            "approved": self.approved,
            "dismissed": self.dismissed,
        }


