# ─── Stage 8: Landed Cost & Variance ─────────────────────────────────────────


@dataclass
class LandedCostBreakdown:
    """Complete landed cost for one shipment, per SKU."""
    id: str = field(default_factory=lambda: str(uuid.uuid4()))
    po_number: str = ""
    sku: str = ""
    cases: int = 0

    # Cost components (per case)
    fob_cost_per_case: float = 0.0
    ocean_freight_per_case: float = 0.0
    fuel_surcharge_per_case: float = 0.0
    origin_charges_per_case: float = 0.0
    insurance_per_case: float = 0.0
    customs_duty_per_case: float = 0.0
    broker_fees_per_case: float = 0.0
    port_charges_per_case: float = 0.0
    demurrage_per_case: float = 0.0
    drayage_per_case: float = 0.0
    exam_fees_per_case: float = 0.0

    shipment_date: str = ""
    supplier_id: str = ""

    @property
    def total_landed_cost_per_case(self) -> float:
        return (
            self.fob_cost_per_case + self.ocean_freight_per_case
            + self.fuel_surcharge_per_case + self.origin_charges_per_case
            + self.insurance_per_case + self.customs_duty_per_case
            + self.broker_fees_per_case + self.port_charges_per_case
            + self.demurrage_per_case + self.drayage_per_case
            + self.exam_fees_per_case
        )

    @property
    def total_shipment_cost(self) -> float:
        return self.total_landed_cost_per_case * self.cases

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "po_number": self.po_number,
            "sku": self.sku,
            "cases": self.cases,
            "cost_per_case": {
                "fob": round(self.fob_cost_per_case, 4),
                "ocean_freight": round(self.ocean_freight_per_case, 4),
                "fuel_surcharge": round(self.fuel_surcharge_per_case, 4),
                "origin_charges": round(self.origin_charges_per_case, 4),
                "insurance": round(self.insurance_per_case, 4),
                "customs_duty": round(self.customs_duty_per_case, 4),
                "broker_fees": round(self.broker_fees_per_case, 4),
                "port_charges": round(self.port_charges_per_case, 4),
                "demurrage": round(self.demurrage_per_case, 4),
                "drayage": round(self.drayage_per_case, 4),
                "exam_fees": round(self.exam_fees_per_case, 4),
                "total": round(self.total_landed_cost_per_case, 4),
            },
            "total_shipment_cost": round(self.total_shipment_cost, 2),
            "shipment_date": self.shipment_date,
        }


