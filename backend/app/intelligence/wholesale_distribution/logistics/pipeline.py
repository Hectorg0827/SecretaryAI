# ─── Master Procurement Cycle ─────────────────────────────────────────────────


@dataclass
class ProcurementCycle:
    """
    Master record tracking the complete lifecycle of one procurement event
    from reorder trigger through warehouse receipt and cost reconciliation.
    """
    id: str = field(default_factory=lambda: str(uuid.uuid4()))
    company_id: str = ""
    stage: ProcurementStage = ProcurementStage.DEMAND_MONITORING
    status: CycleStatus = CycleStatus.OPEN
    supply_chain_type: SupplyChainType = SupplyChainType.OVERSEAS
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    # Linked records (populated as cycle progresses)
    reorder_decision: Optional[ReorderDecisionPackage] = None
    purchase_order: Optional[PurchaseOrder] = None
    vendor_communications: list[VendorCommunication] = field(default_factory=list)
    freight_booking: Optional[FreightBooking] = None
    tracking_events: list[TrackingEvent] = field(default_factory=list)
    customs_events: list[CustomsEvent] = field(default_factory=list)
    warehouse_receipt: Optional[WarehouseReceipt] = None
    landed_costs: list[LandedCostBreakdown] = field(default_factory=list)
    cost_variances: list[CostVariance] = field(default_factory=list)

    # Stage timestamps (ISO)
    stage_timestamps: dict[str, str] = field(default_factory=dict)

    def advance_to(self, stage: ProcurementStage) -> None:
        self.stage = stage
        self.updated_at = datetime.now(timezone.utc).isoformat()
        self.stage_timestamps[stage.value] = self.updated_at

    def days_in_current_stage(self) -> float:
        entered = self.stage_timestamps.get(self.stage.value, self.created_at)
        try:
            start = datetime.fromisoformat(entered.replace("Z", "+00:00"))
            delta = datetime.now(timezone.utc) - start
            return delta.total_seconds() / 86400
        except (ValueError, TypeError):
            return 0.0

    @property
    def po_number(self) -> str:
        return self.purchase_order.po_number if self.purchase_order else ""

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "stage": self.stage.value,
            "status": self.status.value,
            "supply_chain_type": self.supply_chain_type.value,
            "po_number": self.po_number,
            "days_in_current_stage": round(self.days_in_current_stage(), 1),
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "stage_timestamps": self.stage_timestamps,
            "has_freight_booking": self.freight_booking is not None,
            "has_receipt": self.warehouse_receipt is not None,
            "cost_variances": len(self.cost_variances),
            "unresolved_variances": sum(1 for v in self.cost_variances if not v.resolved),
        }
