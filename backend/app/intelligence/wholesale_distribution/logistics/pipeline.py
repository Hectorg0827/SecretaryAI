@dataclass
class PurchaseOrder:
    po_number: str
    supplier_id: str
    supplier_name: str
    supplier_email: str
    ship_to_address: str
    payment_terms: str
    requested_ship_date: str
    language: str = "en"   # "en" | "es" | "fr"
    line_items: list[POLineItem] = field(default_factory=list)
    special_instructions: str = ""
    status: str = "draft"  # draft | sent | confirmed | partially_confirmed | cancelled

    # Populated after confirmation
    confirmed_ship_date: Optional[str] = None
    confirmed_eta: Optional[str] = None
    supplier_ref: str = ""

    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    sent_at: Optional[str] = None
    confirmed_at: Optional[str] = None

    @property
    def total_value(self) -> float:
        return sum(li.total_price for li in self.line_items)

    @property
    def total_cases(self) -> int:
        return sum(li.qty_cases for li in self.line_items)

    def to_dict(self) -> dict:
        return {
            "po_number": self.po_number,
            "supplier_id": self.supplier_id,
            "supplier_name": self.supplier_name,
            "status": self.status,
            "line_items": [li.to_dict() for li in self.line_items],
            "total_value": round(self.total_value, 2),
            "total_cases": self.total_cases,
            "payment_terms": self.payment_terms,
            "requested_ship_date": self.requested_ship_date,
            "confirmed_ship_date": self.confirmed_ship_date,
            "confirmed_eta": self.confirmed_eta,
            "created_at": self.created_at,
            "sent_at": self.sent_at,
        }


